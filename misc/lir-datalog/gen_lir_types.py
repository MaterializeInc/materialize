"""Generates `lir_types.py` from the serde-reflection registry of the LIR format.

The registry, `src/compute-types/tests/snapshots/lir_v1.json`, names every container
reachable from an LIR plan envelope and its serde format. The generated module has one
Python dataclass per struct, newtype struct, tuple struct, unit struct, and enum variant,
and a codec that reads and writes the JSON serde_json produces for the Rust types.

Run `python3 misc/lir-datalog/gen_lir_types.py` to regenerate, then `bin/fmt`. Uses only
the standard library.
"""

import json
import keyword
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REGISTRY = (
    HERE.parent.parent / "src" / "compute-types" / "tests" / "snapshots" / "lir_v1.json"
)
OUTPUT = HERE / "lir_types.py"

# Fields with `#[serde(default)]`, which the registry does not record. Decoding fills
# them in when they are missing. Encoding always writes them, as serde does.
DEFAULTS = {
    ("ColumnOrder", "desc"): False,
    ("ColumnOrder", "nulls_last"): False,
    ("LirAggregateExpr", "distinct"): False,
    ("ReprColumnType", "nullable"): True,
    ("SqlColumnType", "nullable"): True,
    ("SqlRelationType", "keys"): [],
}

# Containers whose registry format does not describe their JSON form. `StableRow` is
# BYTES in the registry, the protobuf encoding of a row. Envelopes write it in the
# readable `{"$row": [...]}` form where every datum has one, which the hand-written
# `Row` class encodes, and in the bytes form otherwise, which `RawStableRow` keeps.
HAND_WRITTEN = {"StableRow": "Row | RawStableRow"}

PRIMITIVES = {
    "BOOL": "bool",
    "U8": "int",
    "U16": "int",
    "U32": "int",
    "U64": "int",
    "U128": "int",
    "I8": "int",
    "I16": "int",
    "I32": "int",
    "I64": "int",
    "I128": "int",
    "F32": "float",
    "F64": "float",
    "CHAR": "str",
    "STR": "str",
    "BYTES": "bytes",
    "UNIT": "None",
}

