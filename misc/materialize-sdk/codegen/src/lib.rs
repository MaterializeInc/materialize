/// Panics on a line of code longer than `limit`, which the language's formatter
/// would wrap, so formatting the repository would make the generated file
/// stale. Comments and docstrings, which no formatter rewraps, may be longer.
pub(crate) fn assert_fits(out: &str, limit: usize, is_text: impl Fn(&str, bool) -> bool) {
    let mut in_docstring = false;
    for line in out.lines() {
        let quotes = line.matches("\"\"\"").count();
        if !is_text(line.trim_start(), in_docstring) && quotes == 0 {
            assert!(
                line.len() <= limit,
                "a generated line over {limit} characters: {line}"
            );
        }
        in_docstring ^= quotes % 2 == 1;
    }
}

/// Prefixes each line of `text`, leaving blank lines without trailing space.
pub(crate) fn prefixed(text: &str, prefix: &str) -> String {
    text.lines()
        .map(|line| {
            if line.is_empty() {
                prefix.trim_end().to_string()
            } else {
                format!("{prefix}{line}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}
