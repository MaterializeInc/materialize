//! Generates each package's types for the values the protocol core hands to
//! bindings, from the JSON Schemas the core derives for them.
//!
//! `schema/values.schema.json` records the schemas, the language-neutral
//! contract. From it this crate generates TypeScript and Python types, and the
//! functions that turn the decimal strings of 64-bit integers into each
//! language's native integers. [`model`] accepts only the schema shapes the
//! core produces and panics on any other, so a type the generators cannot
//! express fails here instead of reaching a package as a wrong type.

// A developer runs the generator, and a panic is how it reports a schema it
// cannot express.
#![allow(
    clippy::panic,
    clippy::expect_used,
    clippy::unwrap_used,
    clippy::indexing_slicing
)]

use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use materialize_sdk_core::{Classification, Event};
use schemars::generate::SchemaSettings;
use serde_json::{Map, Value, json};

mod python;
mod typescript;

/// The values a binding hands to its package's users.
pub const ROOTS: [&str; 2] = ["Event", "Classification"];

/// The JSON Schemas of [`ROOTS`] and everything they reference.
pub fn schema() -> Value {
    let mut generator = SchemaSettings::draft2020_12()
        .for_serialize()
        .into_generator();
    generator.subschema_for::<Event>();
    generator.subschema_for::<Classification>();
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": "Generated by `cargo run -p materialize-sdk-codegen` from the protocol core's types. Do not edit.",
        "$defs": generator.definitions(),
    })
}

/// Every generated file, by its path, and its contents.
pub fn files() -> Vec<(PathBuf, String)> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..");
    let schema = schema();
    let model = model(&schema);
    vec![
        (
            root.join("schema/values.schema.json"),
            format!("{}\n", serde_json::to_string_pretty(&schema).unwrap()),
        ),
        (root.join("node/ts/values.ts"), typescript::types(&model)),
        (
            root.join("node/ts/values_json.ts"),
            typescript::converters(&model),
        ),
        (
            root.join("python/materialize_sdk/_values.py"),
            python::emit(&model),
        ),
    ]
}

/// The definitions the generators emit, roots first.
#[derive(Debug)]
pub struct Model {
    pub defs: Vec<Def>,
}

#[derive(Debug)]
pub struct Def {
    pub name: String,
    pub doc: Option<String>,
    pub kind: Kind,
}

#[derive(Debug)]
pub enum Kind {
    /// One of a set of strings.
    Enum(Vec<EnumValue>),
    Struct(Vec<Field>),
    /// Objects told apart by the string in their `tag` field.
    Union {
        tag: String,
        variants: Vec<Variant>,
    },
}

#[derive(Debug)]
pub struct EnumValue {
    pub value: String,
    pub doc: Option<String>,
}

#[derive(Debug)]
pub struct Variant {
    /// The value of the union's tag field.
    pub tag: String,
    pub doc: Option<String>,
    /// Every field but the tag.
    pub fields: Vec<Field>,
}

#[derive(Debug, Clone)]
pub struct Field {
    pub name: String,
    pub doc: Option<String>,
    pub ty: Ty,
}

#[derive(Debug, Clone, PartialEq)]
pub enum Ty {
    String,
    Bool,
    /// A decimal string, which each package turns into a native integer.
    Integer(Format),
    Nullable(Box<Ty>),
    Array(Box<Ty>),
    Ref(String),
}

/// Union variants or enum values, by definition name.
pub type Seen = BTreeMap<String, BTreeSet<String>>;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Format {
    Uint64,
    Int64,
    /// From 1 to 2^64, one past any `uint64`.
    Frontier,
}

impl Model {
    pub fn def(&self, name: &str) -> &Def {
        self.defs
            .iter()
            .find(|def| def.name == name)
            .unwrap_or_else(|| panic!("no definition {name}"))
    }

    /// Whether a value of `ty` holds a decimal string anywhere.
    pub fn has_integers(&self, ty: &Ty) -> bool {
        match ty {
            Ty::String | Ty::Bool => false,
            Ty::Integer(_) => true,
            Ty::Nullable(ty) | Ty::Array(ty) => self.has_integers(ty),
            Ty::Ref(name) => self.def_has_integers(name),
        }
    }

    pub fn def_has_integers(&self, name: &str) -> bool {
        let fields: Vec<&Field> = match &self.def(name).kind {
            Kind::Enum(_) => vec![],
            Kind::Struct(fields) => fields.iter().collect(),
            Kind::Union { variants, .. } => variants.iter().flat_map(|v| &v.fields).collect(),
        };
        fields.iter().any(|field| self.has_integers(&field.ty))
    }

    /// Checks `value` against the definition `name`, which must hold
    /// exactly the fields the definition lists.
    pub fn check(&self, name: &str, value: &Value) -> Result<(), String> {
        self.check_recording(name, value, &mut Seen::new())
    }

    /// [`Model::check`], recording in `seen` each union variant and enum value
    /// that `value` holds, by definition name.
    pub fn check_recording(
        &self,
        name: &str,
        value: &Value,
        seen: &mut Seen,
    ) -> Result<(), String> {
        self.check_def(self.def(name), value, seen)
            .map_err(|error| format!("{name}: {error}"))
    }

    fn check_def(&self, def: &Def, value: &Value, seen: &mut Seen) -> Result<(), String> {
        match &def.kind {
            Kind::Enum(values) => match value.as_str() {
                Some(s) if values.iter().any(|v| v.value == s) => {
                    seen.entry(def.name.clone()).or_default().insert(s.into());
                    Ok(())
                }
                _ => Err(format!("{value} is not one of the values")),
            },
            Kind::Struct(fields) => self.check_fields(fields, None, value, seen),
            Kind::Union { tag, variants } => {
                let found = value.get(tag).and_then(Value::as_str);
                let variant = variants
                    .iter()
                    .find(|v| Some(v.tag.as_str()) == found)
                    .ok_or_else(|| format!("no variant for {tag} {found:?}"))?;
                seen.entry(def.name.clone())
                    .or_default()
                    .insert(variant.tag.clone());
                self.check_fields(&variant.fields, Some(tag), value, seen)
            }
        }
    }

    /// Every union variant and enum value, by definition name, for comparing
    /// with what [`Model::check_recording`] saw.
    pub fn all_values(&self) -> Seen {
        let mut all = Seen::new();
        for def in &self.defs {
            let values: BTreeSet<String> = match &def.kind {
                Kind::Struct(_) => continue,
                Kind::Enum(values) => values.iter().map(|v| v.value.clone()).collect(),
                Kind::Union { variants, .. } => variants.iter().map(|v| v.tag.clone()).collect(),
            };
            all.insert(def.name.clone(), values);
        }
        all
    }

    fn check_fields(
        &self,
        fields: &[Field],
        tag: Option<&str>,
        value: &Value,
        seen: &mut Seen,
    ) -> Result<(), String> {
        let object = value
            .as_object()
            .ok_or_else(|| format!("{value} is not an object"))?;
        let expected: BTreeSet<&str> = fields.iter().map(|f| f.name.as_str()).chain(tag).collect();
        let found: BTreeSet<&str> = object.keys().map(String::as_str).collect();
        if expected != found {
            return Err(format!("fields {found:?}, expected {expected:?}"));
        }
        for field in fields {
            self.check_ty(&field.ty, &object[&field.name], seen)
                .map_err(|error| format!("{}: {error}", field.name))?;
        }
        Ok(())
    }

    fn check_ty(&self, ty: &Ty, value: &Value, seen: &mut Seen) -> Result<(), String> {
        let ok = match ty {
            Ty::String => value.is_string(),
            Ty::Bool => value.is_boolean(),
            Ty::Integer(format) => value.as_str().is_some_and(|s| format.parses(s)),
            Ty::Nullable(ty) => {
                return if value.is_null() {
                    Ok(())
                } else {
                    self.check_ty(ty, value, seen)
                };
            }
            Ty::Array(ty) => {
                let items = value
                    .as_array()
                    .ok_or_else(|| format!("{value} is not an array"))?;
                return items
                    .iter()
                    .try_for_each(|item| self.check_ty(ty, item, seen));
            }
            Ty::Ref(name) => return self.check_recording(name, value, seen),
        };
        if ok {
            Ok(())
        } else {
            Err(format!("{value} is not {ty:?}"))
        }
    }
}

impl Format {
    fn parse(format: &str) -> Format {
        match format {
            "uint64" => Format::Uint64,
            "int64" => Format::Int64,
            "frontier" => Format::Frontier,
            other => panic!("unknown format {other:?}"),
        }
    }

    /// The pattern the core's schema gives this format. [`Format::parses`] is
    /// what the generators rely on, so a schema with another pattern fails.
    fn pattern(self) -> &'static str {
        match self {
            Format::Uint64 => "^(0|[1-9][0-9]*)$",
            Format::Int64 => "^(0|-?[1-9][0-9]*)$",
            Format::Frontier => "^[1-9][0-9]*$",
        }
    }

    /// Whether `s` is a decimal string of this format, without a sign or
    /// leading zeros the core would not print.
    fn parses(self, s: &str) -> bool {
        let canonical = |n: &dyn ToString| n.to_string() == s;
        match self {
            Format::Uint64 => s.parse::<u64>().is_ok_and(|n| canonical(&n)),
            Format::Int64 => s.parse::<i64>().is_ok_and(|n| canonical(&n)),
            Format::Frontier => s
                .parse::<u128>()
                .is_ok_and(|n| canonical(&n) && (1..=1 << 64).contains(&n)),
        }
    }
}

/// The definitions reachable from [`ROOTS`] through field types. A
/// definition that only a union variant's `$ref` names is merged into that
/// variant instead.
pub fn model(schema: &Value) -> Model {
    let defs = schema["$defs"].as_object().expect("$defs");
    let mut order: Vec<String> = ROOTS.iter().map(|r| r.to_string()).collect();
    let mut parsed = Vec::new();
    let mut next = 0;
    while let Some(name) = order.get(next).cloned() {
        next += 1;
        let def = parse_def(&name, defs);
        for ty in field_types(&def) {
            collect_refs(ty, &mut order);
        }
        parsed.push(def);
    }
    // Every type name, a definition's or a variant's, is distinct.
    let mut names = BTreeSet::new();
    for def in &parsed {
        assert!(
            def.name.starts_with(|c: char| c.is_ascii_uppercase())
                && def.name.chars().all(|c| c.is_ascii_alphanumeric()),
            "{}: not a PascalCase name",
            def.name
        );
        assert!(
            names.insert(def.name.clone()),
            "{} is defined twice",
            def.name
        );
        if let Kind::Union { variants, .. } = &def.kind {
            for variant in variants {
                let name = variant_name(&def.name, &variant.tag);
                assert!(names.insert(name.clone()), "{name} is defined twice");
            }
        }
    }
    Model { defs: parsed }
}

fn field_types(def: &Def) -> Vec<&Ty> {
    match &def.kind {
        Kind::Enum(_) => vec![],
        Kind::Struct(fields) => fields.iter().map(|f| &f.ty).collect(),
        Kind::Union { variants, .. } => variants
            .iter()
            .flat_map(|v| &v.fields)
            .map(|f| &f.ty)
            .collect(),
    }
}

fn collect_refs(ty: &Ty, order: &mut Vec<String>) {
    match ty {
        Ty::Nullable(ty) | Ty::Array(ty) => collect_refs(ty, order),
        Ty::Ref(name) if !order.contains(name) => order.push(name.clone()),
        _ => {}
    }
}

fn object<'a>(value: &'a Value, allowed: &[&str], at: &str) -> &'a Map<String, Value> {
    let object = value
        .as_object()
        .unwrap_or_else(|| panic!("{at}: not an object"));
    for key in object.keys() {
        assert!(
            allowed.contains(&key.as_str()),
            "{at}: unsupported keyword {key:?}"
        );
    }
    object
}

fn description(object: &Map<String, Value>) -> Option<String> {
    object
        .get("description")
        .map(|d| d.as_str().expect("a string description").to_string())
}

fn parse_def(name: &str, defs: &Map<String, Value>) -> Def {
    let schema = defs
        .get(name)
        .unwrap_or_else(|| panic!("no definition {name}"));
    let s = object(
        schema,
        &["description", "type", "properties", "required", "oneOf"],
        name,
    );
    let doc = description(s);
    let Some(one_of) = s.get("oneOf") else {
        assert_eq!(
            s.get("type"),
            Some(&json!("object")),
            "{name}: not an object"
        );
        let fields = fields(s, None, name);
        assert!(!fields.is_empty(), "{name}: an object without fields");
        return Def {
            name: name.into(),
            doc,
            kind: Kind::Struct(fields),
        };
    };
    let variants = one_of.as_array().expect("oneOf is an array");
    if variants.iter().all(|v| v.get("const").is_some()) {
        let values = variants
            .iter()
            .map(|v| {
                let v = object(v, &["const", "description", "type"], name);
                assert_eq!(
                    v.get("type"),
                    Some(&json!("string")),
                    "{name}: a non-string enum"
                );
                EnumValue {
                    value: v["const"].as_str().unwrap().into(),
                    doc: description(v),
                }
            })
            .collect();
        assert!(
            s.get("type").is_none() && s.get("properties").is_none(),
            "{name}: an enum with fields"
        );
        return Def {
            name: name.into(),
            doc,
            kind: Kind::Enum(values),
        };
    }
    // Fields beside `oneOf` are common to every variant, as with a flattened
    // enum.
    let common = if s.contains_key("properties") {
        fields(s, None, name)
    } else {
        vec![]
    };
    let tag = tag_of(variants, name);
    let variants = variants
        .iter()
        .map(|v| {
            let at = format!("{name} variant");
            let v = object(
                v,
                &["description", "type", "properties", "required", "$ref"],
                &at,
            );
            let tag_value = v["properties"][&tag]["const"].as_str().unwrap().to_string();
            assert!(
                is_identifier(&tag_value),
                "{at}: tag {tag_value:?} is not snake_case"
            );
            let at = format!("{name}.{tag_value}");
            let mut fields = common.clone();
            fields.extend(self::fields(v, Some(&tag), &at));
            // A newtype variant names its struct, whose fields it holds.
            if let Some(reference) = v.get("$ref") {
                let referenced = parse_def(ref_name(reference), defs);
                let Kind::Struct(merged) = referenced.kind else {
                    panic!("{at}: $ref to a non-struct");
                };
                fields.extend(merged);
            }
            Variant {
                tag: tag_value,
                doc: description(v),
                fields,
            }
        })
        .collect();
    Def {
        name: name.into(),
        doc,
        kind: Kind::Union { tag, variants },
    }
}

/// The property every variant fixes with a `const`.
fn tag_of(variants: &[Value], name: &str) -> String {
    let consts = |v: &Value| -> BTreeSet<String> {
        v["properties"]
            .as_object()
            .map(|p| {
                p.iter()
                    .filter(|(_, s)| s.get("const").is_some())
                    .map(|(k, _)| k.clone())
                    .collect()
            })
            .unwrap_or_default()
    };
    let mut common = consts(&variants[0]);
    for v in variants {
        common = common.intersection(&consts(v)).cloned().collect();
    }
    assert_eq!(common.len(), 1, "{name}: no single tag among {common:?}");
    let tag = common.pop_first().unwrap();
    assert!(
        is_identifier(&tag),
        "{name}: tag {tag:?} is not a snake_case identifier"
    );
    tag
}

/// The fields of an object schema, in the order of `required`, which is the
/// order the core serializes them. Every field must be required.
fn fields(s: &Map<String, Value>, skip: Option<&str>, at: &str) -> Vec<Field> {
    let empty = Map::new();
    let properties = s
        .get("properties")
        .map_or(&empty, |p| p.as_object().unwrap());
    let required: Vec<&str> = s
        .get("required")
        .map(|r| {
            r.as_array()
                .unwrap()
                .iter()
                .map(|n| n.as_str().unwrap())
                .collect()
        })
        .unwrap_or_default();
    let names: BTreeSet<&str> = properties.keys().map(String::as_str).collect();
    assert_eq!(
        names,
        required.iter().copied().collect::<BTreeSet<_>>(),
        "{at}: an optional field"
    );
    required
        .into_iter()
        .filter(|name| Some(*name) != skip)
        .map(|name| {
            let at = format!("{at}.{name}");
            assert!(is_identifier(name), "{at}: not a snake_case identifier");
            let schema = &properties[name];
            Field {
                name: name.into(),
                doc: schema
                    .get("description")
                    .map(|d| d.as_str().unwrap().into()),
                ty: parse_ty(schema, &at),
            }
        })
        .collect()
}

/// Python's keywords, which are not valid field names of a class-based
/// `TypedDict`.
const PYTHON_KEYWORDS: [&str; 35] = [
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield",
];

/// Whether `name` is snake_case, which both generators can print as is, as a
/// field and in a type name.
fn is_identifier(name: &str) -> bool {
    name.starts_with(|c: char| c.is_ascii_lowercase())
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !PYTHON_KEYWORDS.contains(&name)
}

fn ref_name(reference: &Value) -> &str {
    let reference = reference.as_str().unwrap();
    reference
        .strip_prefix("#/$defs/")
        .unwrap_or_else(|| panic!("unsupported $ref {reference}"))
}

fn parse_ty(schema: &Value, at: &str) -> Ty {
    let s = object(
        schema,
        &[
            "description",
            "type",
            "format",
            "pattern",
            "items",
            "$ref",
            "anyOf",
        ],
        at,
    );
    if let Some(reference) = s.get("$ref") {
        return Ty::Ref(ref_name(reference).into());
    }
    if let Some(any_of) = s.get("anyOf") {
        let [inner, null] = any_of.as_array().unwrap().as_slice() else {
            panic!("{at}: anyOf of other than two");
        };
        assert_eq!(null, &json!({"type": "null"}), "{at}: anyOf without null");
        return Ty::Nullable(Box::new(parse_ty(inner, at)));
    }
    match &s["type"] {
        Value::Array(types) if types.len() == 2 && types[1] == "null" => {
            let mut inner = s.clone();
            inner.insert("type".into(), types[0].clone());
            Ty::Nullable(Box::new(parse_ty(&Value::Object(inner), at)))
        }
        Value::String(t) if t == "string" => {
            let pattern = s.get("pattern").map(|p| p.as_str().unwrap());
            match s.get("format") {
                Some(format) => {
                    let format = Format::parse(format.as_str().unwrap());
                    assert_eq!(
                        pattern,
                        Some(format.pattern()),
                        "{at}: the pattern of {format:?}"
                    );
                    Ty::Integer(format)
                }
                None => {
                    assert_eq!(pattern, None, "{at}: a pattern without a format");
                    Ty::String
                }
            }
        }
        Value::String(t) if t == "boolean" => Ty::Bool,
        Value::String(t) if t == "array" => {
            Ty::Array(Box::new(parse_ty(&s["items"], &format!("{at}[]"))))
        }
        other => panic!("{at}: unsupported type {other}"),
    }
}

/// The text of a Rust doc comment for another language.
///
/// NOTE: the docs of the values the core hands out are read in every language,
/// so they name no Rust item. An intra-doc link fails here instead of reaching
/// a package as a name it does not have.
pub(crate) fn doc_text(doc: &str) -> String {
    assert!(
        !doc.contains("[`"),
        "a Rust intra-doc link in an exported doc: {doc}"
    );
    doc.to_string()
}

/// Splits `Name` or `snake_case` into lowercase words.
pub(crate) fn words(name: &str) -> Vec<String> {
    let mut words: Vec<String> = Vec::new();
    for part in name.split('_') {
        let mut word = String::new();
        for c in part.chars() {
            if c.is_uppercase() && !word.is_empty() {
                words.push(std::mem::take(&mut word));
            }
            word.extend(c.to_lowercase());
        }
        if !word.is_empty() {
            words.push(word);
        }
    }
    words
}

pub(crate) fn pascal(name: &str) -> String {
    words(name)
        .iter()
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

/// The variants' type names, `EventBatch` for the `batch` variant of `Event`.
pub(crate) fn variant_name(def: &str, tag: &str) -> String {
    format!("{def}{}", pascal(tag))
}

