"""Parsers for the comparison output that benchmark steps print to their job log.

These steps run both sides themselves, against the merge base or a named ancestor, so
the movement is already computed in CI and this module only recovers it. Each parser
takes the full job log and returns the movements it found, ignoring everything else.
"""

from __future__ import annotations

import json
import re

from materialize.buildkite_insights.perf_movements.movement import (
    BaselineKind,
    Direction,
    JobRef,
    Movement,
)

# Generated by materialize/feature_benchmark/report.py.
FEATURE_BENCHMARK_HEADER = re.compile(
    r"^NAME\s+\|\s*TYPE\s+\|\s*THIS\s+\|\s*OTHER\s+\|\s*UNIT\s*\|"
)

# Generated by test/parallel-benchmark/mzcompose.py.
PARALLEL_BENCHMARK_HEADER = re.compile(
    r"^QUERY\s+\|\s*STAT\s+\|\s*THIS\s+\|\s*OTHER\s+\|\s*CHANGE\s+\|"
)
PARALLEL_BENCHMARK_SCENARIO = re.compile(r"^Comparing scenario (?P<scenario>\S+)\s*$")

# Generated by ScalabilityChange.__str__ in materialize/scalability/result/scalability_change.py.
SCALABILITY_CHANGE = re.compile(
    r"^\*\s+(?P<kind>Regression|Scalability improvement)"
    r" in workload '(?P<workload>[^']+)'"
    r" at concurrency (?P<concurrency>\d+)"
    r" with (?P<endpoint>.+?):"
    r"\s+(?P<this>-?[\d.]+) tps vs\. (?P<baseline>-?[\d.]+) tps"
    r"\s+\((?P<diff>-?[\d.]+) tps; (?P<percent>-?[\d.]+)%\)\s*$"
)

# Statistics as defined by the parallel benchmark's own Statistics class: durations are
# milliseconds, `qps` is queries per second and `queries` is a count over the load phase.
# `slope` is a millisecond-per-second drift whose ratio against a baseline near zero says
# nothing, so it is left out rather than ranked. A statistic absent here is skipped, so a
# newly added one is missing from the report rather than silently mislabelled.
_PARALLEL_BENCHMARK_STATS: dict[str, tuple[Direction, str | None]] = {
    "qps": (Direction.HIGHER_IS_BETTER, "qps"),
    "queries": (Direction.HIGHER_IS_BETTER, None),
    "avg": (Direction.LOWER_IS_BETTER, "ms"),
    "min": (Direction.LOWER_IS_BETTER, "ms"),
    "max": (Direction.LOWER_IS_BETTER, "ms"),
    "p50": (Direction.LOWER_IS_BETTER, "ms"),
    "p95": (Direction.LOWER_IS_BETTER, "ms"),
    "p99": (Direction.LOWER_IS_BETTER, "ms"),
    "p99_9": (Direction.LOWER_IS_BETTER, "ms"),
    "p99_99": (Direction.LOWER_IS_BETTER, "ms"),
    "p99_999": (Direction.LOWER_IS_BETTER, "ms"),
    "p99_9999": (Direction.LOWER_IS_BETTER, "ms"),
    "p99_99999": (Direction.LOWER_IS_BETTER, "ms"),
    "p99_999999": (Direction.LOWER_IS_BETTER, "ms"),
    "std": (Direction.LOWER_IS_BETTER, "ms"),
}


def normalize_log_text(raw: str) -> str:
    """Return a job log as newline-separated plain text.

    Buildkite serves logs as JSON, and the MCP server saves them as a `{"entries": [{"c":
    ...}]}` document despite announcing plain text. Both shapes reach this module, and a
    JSON document fed to the line-anchored table regexes matches nothing at all, so the
    failure would be an empty report rather than an error. Anything that is not
    recognizable JSON is passed through untouched.
    """
    stripped = raw.lstrip()
    if not stripped.startswith(("{", "[")):
        return raw

    try:
        document = json.loads(raw)
    except json.JSONDecodeError:
        return raw

    if isinstance(document, dict):
        if isinstance(document.get("content"), str):
            return document["content"]
        entries = document.get("entries")
    else:
        entries = document

    if isinstance(entries, list):
        lines = [entry["c"] for entry in entries if isinstance(entry, dict) and "c" in entry]
        if lines:
            return "\n".join(lines)

    return raw


def _parse_float(value: str) -> float | None:
    try:
        return float(value.strip())
    except ValueError:
        return None


def _parse_percent(value: str) -> float | None:
    stripped = value.strip().rstrip("%").strip()
    if not stripped:
        return None
    return _parse_float(stripped)


def _parse_verdict(value: str) -> bool | None:
    stripped = value.strip()
    if not stripped:
        return None
    return stripped.upper().strip("!") == "YES"


def _split_row(line: str, expected_cells: int) -> list[str] | None:
    cells = line.split("|")
    if len(cells) != expected_cells:
        return None
    return cells


def parse_feature_benchmark_log(text: str, job: JobRef) -> list[Movement]:
    """Recover the feature benchmark's THIS-against-OTHER table.

    Every metric the feature benchmark reports is lower-is-better, which its evaluator
    asserts, so the human-readable verdict column carries no information this needs. A
    row the runner could not compare, printed when only the THIS side ran, drops out
    because its numeric cells do not parse. The log holds one table per cycle plus the reruns of any
    scenario that regressed; the last table a given scenario appears in is the one the
    runner settled on, so later rows overwrite earlier ones.
    """
    by_key: dict[tuple[str, str], Movement] = {}

    in_table = False
    for line in normalize_log_text(text).splitlines():
        if FEATURE_BENCHMARK_HEADER.match(line):
            in_table = True
            continue
        if not in_table:
            continue

        cells = _split_row(line, 8)
        if cells is None:
            # The dashed rule under the header is not a row; anything else ends the table.
            if not line.strip().startswith("---"):
                in_table = False
            continue

        scenario = cells[0].strip()
        metric = cells[1].strip()
        this = _parse_float(cells[2])
        other = _parse_float(cells[3])
        if not scenario or not metric or this is None or other is None:
            continue

        by_key[(scenario, metric)] = Movement(
            job=job,
            scenario=scenario,
            metric=metric,
            this=this,
            baseline=other,
            direction=Direction.LOWER_IS_BETTER,
            baseline_kind=BaselineKind.JOB_COMPARISON,
            unit=cells[4].strip() or None,
            threshold_percent=_parse_percent(cells[5]),
            reported_regression=_parse_verdict(cells[6]),
        )

    return list(by_key.values())


def parse_parallel_benchmark_log(text: str, job: JobRef) -> list[Movement]:
    """Recover the parallel benchmark's per-query comparison tables.

    The QUERY cell is truncated to 40 characters by the printer, so the scenario name
    that precedes each table is what disambiguates otherwise identical query prefixes.
    """
    movements = []
    scenario = None
    in_table = False

    for line in normalize_log_text(text).splitlines():
        scenario_match = PARALLEL_BENCHMARK_SCENARIO.match(line)
        if scenario_match:
            scenario = scenario_match.group("scenario")
            continue

        if PARALLEL_BENCHMARK_HEADER.match(line):
            in_table = True
            continue
        if not in_table:
            continue

        cells = _split_row(line, 7)
        if cells is None:
            if not line.strip().startswith("---"):
                in_table = False
            continue

        query = cells[0].strip()
        stat = cells[1].strip()
        this = _parse_float(cells[2])
        other = _parse_float(cells[3])
        if not query or not stat or this is None or other is None:
            continue

        known_stat = _PARALLEL_BENCHMARK_STATS.get(stat)
        if known_stat is None:
            continue
        direction, unit = known_stat
        name = f"{scenario}/{query}" if scenario else query

        movements.append(
            Movement(
                job=job,
                scenario=name,
                metric=stat,
                this=this,
                baseline=other,
                direction=direction,
                baseline_kind=BaselineKind.JOB_COMPARISON,
                unit=unit,
                threshold_percent=_parse_percent(cells[5]),
                reported_regression=_parse_verdict(cells[6]),
            )
        )

    return movements


def parse_scalability_log(text: str, job: JobRef) -> list[Movement]:
    """Recover the scalability framework's regression and improvement bullets.

    The framework emits a bullet only for a change it already judged significant, so
    every line found here is a movement; there is no sub-threshold noise to filter.
    """
    movements = []

    for line in normalize_log_text(text).splitlines():
        match = SCALABILITY_CHANGE.match(line.strip())
        if match is None:
            continue

        this = _parse_float(match.group("this"))
        baseline = _parse_float(match.group("baseline"))
        if this is None or baseline is None:
            continue

        movements.append(
            Movement(
                job=job,
                scenario=f"{match.group('workload')} @ concurrency {match.group('concurrency')}",
                metric="tps",
                this=this,
                baseline=baseline,
                direction=Direction.HIGHER_IS_BETTER,
                baseline_kind=BaselineKind.JOB_COMPARISON,
                unit="tps",
                reported_regression=match.group("kind") == "Regression",
            )
        )

    return movements
