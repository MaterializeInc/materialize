/// Returns the text that `regproc` OID `oid` renders as, or `None` when no
/// builtin function has that OID.
///
/// PostgreSQL renders an unmatched OID in decimal and OID 0 as `-`. Neither is
/// in [`NAMES`], so callers handle both.
pub fn name(oid: u32) -> Option<&'static str> {
    NAMES
        .binary_search_by_key(&oid, |(entry_oid, _)| *entry_oid)
        .ok()
        .map(|i| NAMES[i].1)
}

/// Returns the OID whose [`NAMES`] rendering is `name`.
///
/// `Err` distinguishes no match from an ambiguous one. A rendering is ambiguous
/// when several overloads share it, in which case PostgreSQL's `regprocin`
/// likewise refuses to resolve it. The scan is linear because reads of this
/// direction only happen while decoding text-format input, which is rare
/// compared to encoding.
pub fn oid(name: &str) -> Result<u32, NameLookupError> {
    let mut found = None;
    for (entry_oid, entry_name) in NAMES {
        if *entry_name == name {
            if found.is_some() {
                return Err(NameLookupError::Ambiguous);
            }
            found = Some(*entry_oid);
        }
    }
    found.ok_or(NameLookupError::NotFound)
}

/// Why [`oid`] could not resolve a name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NameLookupError {
    /// No builtin function renders as the given name.
    NotFound,
    /// Several builtin functions render as the given name.
    Ambiguous,
}
